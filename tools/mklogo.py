#!/usr/bin/env python3
"""Convert an image into a palette-indexed RLE C header for the venus shim.

Converts a PNG/JPG into the shim boot-logo header (256-colour palette + RLE).
shim/build.sh runs it when SHIM_LOGO_IMAGE is set. The source image is never
committed to the repo, and neither is the generated header (shim/out is ignored).

Usage: python -I tools/mklogo.py <in.png|jpg> <out.h> [--max 400]

The image is shrunk (never enlarged) so its longer side is at most --max,
quantized to 256 colours (median cut, Floyd-Steinberg dither), and the
row-major palette indices are written as (run, index) byte pairs. Runs are
1..255 pixels and may wrap across rows. shim/console.c con_logo() consumes it.
"""
import argparse

from PIL import Image

PAL_N = 256
RLE_PER_LINE = 16


def rle_encode(idx):
    out = bytearray()
    i, n = 0, len(idx)
    while i < n:
        v = idx[i]
        j = i + 1
        while j < n and idx[j] == v and j - i < 255:
            j += 1
        out += bytes((j - i, v))
        i = j
    return bytes(out)


def rle_decode(rle):
    out = bytearray()
    for k in range(0, len(rle), 2):
        out += bytes((rle[k + 1],)) * rle[k]
    return bytes(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('src')
    ap.add_argument('out')
    ap.add_argument('--max', type=int, default=400, help='limit for the longer side, pixels')
    a = ap.parse_args()
    if a.max < 1:
        ap.error('--max must be >= 1')

    img = Image.open(a.src).convert('RGB')
    w, h = img.size
    if max(w, h) > a.max:
        s = a.max / max(w, h)
        w, h = max(1, round(w * s)), max(1, round(h * s))
        img = img.resize((w, h), Image.Resampling.LANCZOS)

    q = img.quantize(colors=256, method=Image.Quantize.MEDIANCUT,
                     dither=Image.Dither.FLOYDSTEINBERG)
    raw = q.getpalette() or []
    pal = []
    for i in range(PAL_N):
        if 3 * i + 2 < len(raw):
            r, g, b = raw[3 * i:3 * i + 3]
            pal.append(0xff000000 | r << 16 | g << 8 | b)
        else:
            pal.append(0xff000000)

    idx = q.tobytes()
    assert len(idx) == w * h
    rle = rle_encode(idx)
    if rle_decode(rle) != idx:
        raise RuntimeError('RLE decode self-check failed')

    lines = [
        '/* generated by tools/mklogo.py: %dx%d, palette RLE (run, index) pairs */' % (w, h),
        '#ifndef SHIM_LOGO_H',
        '#define SHIM_LOGO_H',
        '',
        '#include <stdint.h>',
        '',
        '#define LOGO_W %d' % w,
        '#define LOGO_H %d' % h,
        'static const uint32_t logo_pal[256] = {',
    ]
    for i in range(0, PAL_N, 8):
        lines.append('\t' + ','.join('0x%08x' % v for v in pal[i:i + 8]) + ',')
    lines.append('};')
    lines.append('static const uint8_t logo_rle[] = {')
    for i in range(0, len(rle), RLE_PER_LINE):
        lines.append('\t' + ','.join('0x%02x' % b for b in rle[i:i + RLE_PER_LINE]) + ',')
    lines.append('};')
    lines.append('#define LOGO_RLE_LEN %d' % len(rle))
    lines += ['', '#endif', '']
    with open(a.out, 'w', newline='\n') as f:
        f.write('\n'.join(lines))

    print('w=%d h=%d rle_bytes=%d' % (w, h, len(rle)))


if __name__ == '__main__':
    main()
